def ratio_hint(
    problem: dict, text: str, continuation: tuple[str, str] | None = None,
) -> tuple[str, tuple[str, str] | None] | None:
    from tutor.triangle_reasoning import ratio_followup_feedback, ratio_followup_question, ratio_step_feedback

    question, previous_language = continuation or (None, None)
    followup = ratio_followup_feedback(problem, text, question) if question else None
    verdict, detail = followup or ratio_step_feedback(problem, text)
    if verdict == 'unsupported':
        return None
    key = detail
    if verdict == 'definition_mismatch' and detail != 'reversed_order':
        key = 'mismatch_' + detail
    elif verdict == 'partial_correct':
        key = 'partial_' + detail

    language = guess_language(text)
    if language == 'en' and any('\u0900' <= char <= '\u097f' for char in text):
        language = 'hi'
    if language == 'en' and _HINGLISH_CUE.search(text):
        language = 'hinglish'
    if followup and language == 'en':
        language = previous_language

    if followup and verdict == 'clarify' and (key.startswith(('retry_', 'setup_')) or key == 'other_side'):
        next_question = question
    elif followup and key == 'diagram_labels':
        next_question = question
    else:
        next_question = ratio_followup_question(key, text)
    return HINT_TEXT[language][key.partition(':')[0]], (next_question, language) if next_question else None
