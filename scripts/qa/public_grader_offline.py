"""Offline robustness check of the answer grader on real, human-written final answers (GSM8K test, MATH algebra and
precalculus test items whose boxed answer is a plain number, fraction or surd).

Usage (canonical workspace cwd, shared-checkout .venv, with -I because the inputs are downloads):
  python -I public_grader_offline.py [--out FILE]
For every gold answer the grader must ACCEPT the forms a student plausibly writes and REJECT near misses. The forms are
generated by this script from the real answers, so this tests parsing and equivalence, not the datasets' labels.
"""
from __future__ import annotations

import argparse
import collections
import json
import re
import sys
from fractions import Fraction
from pathlib import Path

import pandas as pd

MAIN = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(MAIN / "src"))
from tutor import mathcore  # noqa: E402

SRC = Path(r"D:/Work/IITB/Socratic Tutor/Directions/external_datasets")


def boxed(solution):
    i = solution.rfind("\\boxed{")
    if i < 0:
        return None
    depth, j = 0, i + 7
    for k in range(j, len(solution)):
        if solution[k] == "{":
            depth += 1
        elif solution[k] == "}":
            if depth == 0:
                return solution[j:k]
            depth -= 1
    return None


def latex_to_plain(tex):
    """Plain numbers, fractions and surds only; anything else is skipped (returns None)."""
    t = tex.replace("\\dfrac", "\\frac").replace("\\tfrac", "\\frac").replace("\\!", "").replace(" ", "").replace("$", "")
    t = re.sub(r"\\frac\{([^{}]+)\}\{([^{}]+)\}", r"(\1)/(\2)", t)
    t = re.sub(r"\\sqrt\{([^{}]+)\}", r"sqrt(\1)", t)
    t = re.sub(r"\\sqrt(\d)", r"sqrt(\1)", t)
    if "\\" in t or not re.fullmatch(r"(?:[-+0-9().*/]|sqrt)+", t):
        return None
    t = re.sub(r"(\d)(sqrt|\()", r"\1*\2", t)
    try:                                       # keep only answers the maths kernel itself can read
        mathcore.grade({"kind": "scalar", "value": t}, {"kind": "scalar", "value": t})
    except Exception:
        return None
    return t


def items():
    for r in pd.read_parquet(SRC / "gsm8k/main__test-00000-of-00001.parquet").itertuples():
        gold = r.answer.split("####")[-1].strip().replace(",", "")
        if re.fullmatch(r"-?\d+(\.\d+)?", gold):
            yield {"source": "gsm8k", "gold": gold}
    for f in ("algebra__test-00000-of-00001.parquet", "precalculus__test-00000-of-00001.parquet"):
        for r in pd.read_parquet(SRC / "math_algebra_precalc" / f).itertuples():
            b = boxed(r.solution)
            plain = latex_to_plain(b) if b else None
            if plain:
                yield {"source": "math_" + f.split("__")[0], "gold": plain, "latex": b}


def forms(gold):
    accept = [gold, f"The answer is {gold}", f"x = {gold}", f"  {gold}  "]
    reject = []
    try:
        value = Fraction(gold) if re.fullmatch(r"-?\d+(\.\d+)?", gold) else None
    except ValueError:
        value = None
    if value is not None:
        if value.denominator == 1:
            n = int(value)
            accept += [f"{n}.0", f"{n * 2}/2"]
            if abs(n) >= 1000:
                accept.append(f"{n:,}")                       # Indian students often write 1,000 or 1,00,000
            reject += [str(n + 1), str(n - 1)] + ([str(n * 10)] if n else [])   # 0 * 10 is still 0
        else:
            accept.append(str(value))                          # decimal written as a fraction
            reject.append(str(value + 1))
    else:
        reject += [f"({gold})+1", f"2*({gold})"]
    return accept, reject


def run_one(text, gold):
    key = {"kind": "scalar", "value": gold}
    try:
        parsed = mathcore.parse_answer(text, key)
        if not parsed.get("ok"):
            return "not_parsed"
        return mathcore.grade(parsed["typed"], {"kind": "scalar", "value": gold})["status"]
    except Exception as exc:                   # a crash on student input is itself a finding
        return "grader_error:" + type(exc).__name__


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out")
    args = ap.parse_args()
    results = collections.defaultdict(lambda: collections.Counter())
    failures = collections.defaultdict(list)
    n_items = collections.Counter()
    for it in items():
        n_items[it["source"]] += 1
        accept, reject = forms(it["gold"])
        for i, text in enumerate(accept):
            status = run_one(text, it["gold"])
            form = ["plain", "the_answer_is", "x_equals", "spaces", "decimal_or_ratio", "ratio", "commas"][min(i, 6)] if i < 4 else \
                ("commas" if "," in text else "equivalent_form")
            results[(it["source"], "accept", form)][status] += 1
            if status != "correct" and len(failures[(it["source"], form)]) < 5:
                failures[(it["source"], form)].append({"gold": it["gold"], "given": text, "status": status})
        for text in reject:
            status = run_one(text, it["gold"])
            results[(it["source"], "reject", "near_miss")][status] += 1
            if status == "correct" and len(failures[(it["source"], "near_miss")]) < 5:
                failures[(it["source"], "near_miss")].append({"gold": it["gold"], "given": text, "status": status})
    table = {f"{s} | {kind} | {form}": dict(c) for (s, kind, form), c in sorted(results.items())}
    print("items:", dict(n_items))
    for k, v in table.items():
        print(f"  {k:52s} {v}")
    out = {"items": dict(n_items), "results": table, "failure_examples": {f"{s} | {f}": v for (s, f), v in failures.items()}}
    if args.out:
        Path(args.out).write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")


if __name__ == "__main__":
    main()
